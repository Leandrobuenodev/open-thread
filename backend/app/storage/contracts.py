"""Small storage boundary: atomic entity batches within one owner partition."""

from typing import Protocol


class StorageError(Exception):
    pass


class StorageConflict(StorageError):
    pass


class EntityRepository(Protocol):
    def get(self, partition: str, row: str) -> dict | None: ...
    def query(self, partition: str, prefix: str) -> list[dict]: ...
    def batch(self, operations: list[tuple[str, dict]]) -> None: ...
    def close(self) -> None: ...


class ObjectStorage(Protocol):
    def put(self, reference: str, content: bytes) -> None: ...
    def read(self, reference: str) -> bytes: ...
    def remove(self, reference: str) -> None: ...
    def remove_prefix(self, prefix: str) -> None: ...
    def close(self) -> None: ...
